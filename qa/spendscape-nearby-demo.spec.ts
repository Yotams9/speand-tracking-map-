import { test, expect, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
const out = 'artifacts/spendscape-nearby-demo/correction'
const qa = (page: Page) => page.evaluate(() => (window as any).__SPENDSCAPE_QA__)
async function receipt(page: Page, width = 1280, he = false) {
  await page.setViewportSize({ width, height: width === 360 ? 640 : width === 430 ? 932 : 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.waitForFunction(() => (window as any).__SPENDSCAPE_QA__?.ready)
  if (he) await page.getByRole('button', { name: 'Switch to Hebrew' }).click()
  await page.getByTestId(width < 761 ? 'capture-open-mobile' : 'capture-open-desktop').click()
  await page.getByTestId('capture-scan').click()
  await expect(page.getByTestId('capture-confirm')).toBeVisible()
  expect(await qa(page)).toMatchObject({ combinedPurchaseCount: 42, canonicalPins: 12 })
  await expect(page.getByTestId('nearby-demo')).toHaveCount(0)
  await page.clock.install({ time: new Date('2026-09-24T12:00:00Z') })
  await page.clock.pauseAt(new Date('2026-09-24T12:00:10Z'))
}
async function save(page: Page) {
  await page.getByTestId('capture-confirm').click()
  await expect(page.getByTestId('capture-success')).toBeVisible()
}
test.beforeAll(async () => { await mkdir(out, { recursive: true }) })
for (const [width, he] of [[1280, false], [360, false], [360, true], [390, false], [390, true], [430, false], [430, true]] as const) {
  test(`receipt save expiry comparison ${width} ${he ? 'he' : 'en'}`, async ({ page, context }) => {
    const errors: string[] = [], writes: string[] = [], prohibited: string[] = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('request', r => {
      if (r.method() !== 'GET') writes.push(r.method())
      if (/tesseract|traineddata|nearby-prices|nominatim|pricesprodpublic/i.test(r.url())) prohibited.push('unexpected-source')
    })
    await receipt(page, width, he)
    await save(page)
    await page.clock.runFor(7999)
    await expect(page.getByTestId('capture-undo')).toBeVisible()
    await expect(page.getByTestId('nearby-demo')).toHaveCount(0)
    await page.clock.runFor(1)
    await expect(page.getByTestId('capture-undo')).toHaveCount(0)
    const card = page.getByTestId('nearby-demo')
    await expect(card).toBeVisible()
    await expect(card).toContainText(he ? '2 מתוך 4' : '2 of 4')
    await expect(card).toContainText(he ? 'לא חיסכון על הסל המלא' : 'not a saving on the whole basket')
    await expect(card).toContainText('5.50')
    await expect(card).toContainText(he ? 'חנות בדיונית' : 'fictional store')
    await card.locator('summary').click()
    await expect(card).toContainText('43.40'); await expect(card).toContainText('37.90')
    await card.scrollIntoViewIfNeeded()
    await page.screenshot({ path: `${out}/capture-${width}-${he ? 'he' : 'en'}.png` })
    expect(await qa(page)).toMatchObject({ sessionPurchaseCount: 1, combinedPurchaseCount: 43, canonicalPins: 12, mapInstanceCount: 1, mapConstructionCount: 1, analytics: { totalBaseAmountIls: 6864.28 } })
    await page.getByTestId('capture-done').click()
    await expect(card).toBeInViewport({ ratio: 1 })
    await expect(card.locator('details')).not.toHaveAttribute('open', '')
    await expect(card.getByText('629', { exact: false }).filter({ visible: true })).toBeVisible()
    const bounds = await card.boundingBox()
    if (width < 761) expect(bounds!.height).toBeLessThanOrEqual(200)
    await page.screenshot({ path: `${out}/globe-${width}-${he ? 'he' : 'en'}.png` })
    await card.locator('summary').focus()
    await page.keyboard.press('Enter')
    await expect(card.locator('details')).toHaveAttribute('open', '')
    await expect(card.locator('details')).toContainText('43.40')
    await page.screenshot({ path: `${out}/globe-expanded-${width}-${he ? 'he' : 'en'}.png` })
    await page.keyboard.press('Space')
    await expect(card.locator('details')).not.toHaveAttribute('open', '')
    console.log(`comparison ${width} ${he ? 'he' : 'en'} collapsed height=${bounds!.height}`)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await card.getByRole('button').click()
    await expect(card).toHaveCount(0)
    expect(await context.storageState()).toEqual({ cookies: [], origins: [] })
    expect(writes).toEqual([]); expect(prohibited).toEqual([]); expect(errors).toEqual([])
    await page.clock.resume()
    await page.reload(); await page.waitForFunction(() => (window as any).__SPENDSCAPE_QA__?.ready)
    expect((await qa(page)).combinedPurchaseCount).toBe(42)
    await expect(card).toHaveCount(0)
  })
}
for (const external of [false, true]) {
  test(`Undo prevents delayed comparison ${external ? 'external' : 'Capture'}`, async ({ page }) => {
    await receipt(page); await save(page)
    await page.clock.runFor(4000)
    if (external) await page.getByTestId('capture-done').click()
    await page.getByTestId(external ? 'session-undo' : 'capture-undo').click()
    await page.clock.runFor(10000)
    await expect(page.getByTestId('nearby-demo')).toHaveCount(0)
    expect((await qa(page)).combinedPurchaseCount).toBe(42)
  })
}
test('leaving Capture during Undo shows the comparison only at expiry; Reset removes it', async ({ page }) => {
  await receipt(page); await save(page)
  await page.getByTestId('capture-done').click()
  await page.clock.runFor(7999); await expect(page.getByTestId('nearby-demo')).toHaveCount(0)
  await page.clock.runFor(1); await expect(page.getByTestId('nearby-demo')).toBeVisible()
  await page.getByTestId('capture-open-desktop').click()
  await page.getByRole('button', { name: 'Reset demo additions' }).click()
  await page.getByRole('button', { name: 'Close Capture', exact: true }).last().click()
  await expect(page.getByTestId('nearby-demo')).toHaveCount(0)
  expect((await qa(page)).combinedPurchaseCount).toBe(42)
})
